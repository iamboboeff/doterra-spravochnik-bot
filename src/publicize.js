const DIRECT_NAMES = [
  'Александр',
  'Алиса',
  'Анастасия',
  'Анна',
  'Анют',
  'Аня',
  'Вика',
  'Елена',
  'Ира',
  'Ирин',
  'Ирина',
  'Катя',
  'Лена',
  'Маш',
  'Мария',
  'Надежда',
  'Оля',
  'Саша',
  'Светлана',
  'Тамара',
  'Татьяна',
  'Юля',
];

const namesPattern = new RegExp(
  `^(?:${DIRECT_NAMES.join('|')})\\s*[,!]\\s*`,
  'iu'
);

const greetingPrefix =
  /^(?:(?:добрый|доброе|доьрое|дрррый|доброго|доброй)\s+(?:день|вечер|утро|ночи|дня)|здравствуйте|здравствуй|привет)(?:\s+всем)?\s*[!,.—–-]*\s*/iu;

const greetingOnly =
  /^(?:(?:добрый|доброе|доьрое|дрррый|доброго|доброй)\s+(?:день|вечер|утро|ночи|дня)|здравствуйте|здравствуй|привет)(?:\s+всем)?\s*[!,.—–-]*$/iu;

const chatOnlyLine =
  /^(?:вот\s+здесь|здесь\s+вс[её]|тут\s+вс[её]|про\s+.+\s+писал[аи]?\s+(?:уже\s+)?(?:выше|тут)|если\s+.+\s+пришлю\s+в\s+лс|у\s+меня\s+есть\s+лекция|скину\s+в\s+лс|пришлю\s+в\s+лс|смотрите\s+по\s+ссылке|читайте\s+здесь)(?:\s|$)/iu;

const acknowledgementOnly =
  /^(?:да[,\s]+(?:именно\s+так|полностью\s+согласна|согласна)|спасибо(?:\s+большое)?|поняла|вижу|ну\s+и\s+правильно)\s*[!.🙏]*$/iu;

function sentenceCase(value) {
  if (!value) return value;
  return value[0].toLocaleUpperCase('ru-RU') + value.slice(1);
}

function cleanLine(rawLine) {
  let line = rawLine.trim();
  if (!line) return '';
  if (/^#/u.test(line)) return '';
  if (greetingOnly.test(line) || acknowledgementOnly.test(line)) return '';

  line = line.replace(namesPattern, '');
  line = line.replace(greetingPrefix, '');
  if (!line || greetingOnly.test(line) || acknowledgementOnly.test(line)) return '';
  if (
    /^(?:Возраст\s+я\s+не\s+спросил[аи]|Зачем\s+он\s+Вам|Судя\s+по\s+возрасту|Не\s+могу[^.]*кому\s+отвечал[аи]|Не\s+найд[еу][тм][^.]*(?:в\s+)?переписке|У\s+меня\s+есть\s+лекция|Не\s+знаю,\s*понятно\s+ли\s+написал[аи]|Скоро\s+размещу\s+здесь|Ну\s+и\s+правильно\s+что\s+не\s+принимает|Я\s+уже\s+выше\s+объяснял[аи]|Я\s+готовлю\s+пост\s+на\s+эту\s+тему)/iu.test(line)
  ) {
    return '';
  }

  line = line
    .replace(
      /^Простите,\s*никогда\s+не\s+пользуюсь\s+препаратами\s+аптечными[^.]*Это\s+гормональный\s+препарат/iu,
      'При оценке препарата важно смотреть на действующее вещество. В данном случае препарат является гормональным.'
    )
    .replace(
      /^Это\s+может\s+быть\s+и\s+застой\s+желчи\s+А\s+также/iu,
      'Среди возможных причин — застой желчи. Также'
    )
    .replace(/^Имею\s+ввиду,\s*что/iu, '')
    .replace(
      /^Очень\s+похоже\s+на\s+укус\s+и\s+такая\s+реакция\s+пошла\s+Может\s+мошка\s+какая/iu,
      'Такая реакция может возникнуть после укуса насекомого, например мошки.'
    )
    .replace(
      /^Стоматит\s+в\s+виде\s+язв\s+если\s*-?\s*то\s+это\s+герпесный\s+\(\s*афтозный\s+называется\s*\)/iu,
      'Язвенный стоматит может иметь афтозную форму.'
    )
    .replace(
      /^А\s+Кандидоз\s+полости\s+рта\s+-?\s*это\s+другое\s*,?\s*это\s+как\s+молочница\s*,?\s*только\s+в\s+полости\s+рта/iu,
      'Кандидоз полости рта — отдельное состояние, которое также называют молочницей полости рта.'
    )
    .replace(/Сукровичный\s+цвет\s+-?\s*не\s+пугайтесь/iu, 'Сукровичный цвет выделений возможен.')
    .replace(/Всегда\s+изучайте\s+состав/iu, 'Важно изучать состав')
    .replace(/Смотрите\s+действующее\s+вещество/iu, 'Следует смотреть на действующее вещество');

  line = line
    .replace(/https:\/\/t\.me\/c\/1593559029\/\d+/giu, '')
    .replace(/\(\s*продолжение\s*\)/giu, '')
    .replace(/см\.?\s*(?:ссылку\s+)?выше/giu, 'см. соответствующую тему справочника')
    .replace(/как\s+(?:я\s+)?писал[аи]?\s+выше/giu, 'как отмечено в соответствующей теме справочника')
    .replace(/выше\s+я\s+писал[аи]?\s+про/giu, 'в справочнике также есть материал про')
    .replace(/об\s+этом\s+(?:я\s+)?рассказываю\s+выше/giu, 'это описано в соответствующей теме справочника')
    .replace(/по\s+ссылке\s+(?:выше\s+)?вс[её]\s+показываю/giu, 'подробности приведены в соответствующей теме справочника')
    .replace(/если\s+вы\s+видите/giu, 'если наблюдаются')
    .replace(/если\s+вы/giu, 'если')
    .replace(/если\s+точно\s+знаете/giu, 'если точно известно')
    .replace(/вы\s+можете/giu, 'можно')
    .replace(/вы\s+должны\s+понимать/giu, 'важно понимать')
    .replace(/вам\s+нужно/giu, 'необходимо')
    .replace(/у\s+вашего\s+реб[её]нка/giu, 'у ребёнка')
    .replace(/вашему\s+реб[её]нку/giu, 'ребёнку')
    .replace(/ваш\s+реб[её]нок/giu, 'ребёнок')
    .replace(/у\s+вас/giu, 'в такой ситуации')
    .replace(/чтоб(?:ы)?\s+вам\s+спокойнее\s+было/giu, 'для спокойствия')
    .replace(/чтобы\s+вам\s+было\s+спокойнее/giu, 'для спокойствия')
    .replace(/я\s+бы\s+(?:здесь\s+)?(?:точно\s+)?/giu, 'можно ')
    .replace(/я\s+рекомендую/giu, 'рекомендуется')
    .replace(/я\s+советую/giu, 'рекомендуется')
    .replace(/у\s+меня/giu, 'в практике автора')
    .replace(/мне\s+кажется/giu, 'по наблюдению автора')
    .replace(/мой\s+реб[её]нок/giu, 'ребёнок автора')
    .replace(/мой\s+сын/giu, 'сын автора')
    .replace(/моя\s+дочь/giu, 'дочь автора')
    .replace(/отвечаю\s+по\s+поводу/giu, 'Информация по теме:')
    .replace(/держите\s+удобную/giu, 'Ниже приведена')
    .replace(/Возраст\s+я\s+не\s+спросил[аи],?\s+сколько\s+лет\s+(?:мальчику|девочке)\??/giu, '')
    .replace(/Думаю,\s*Вы\s+уже\s+знаете\s*,?\s*как\s+справляться\s+с\s+жаром[!]*/giu, '')
    .replace(/Зачем\s+он\s+Вам\s*\?+!*/giu, '')
    .replace(/что\s+масла\s+ваши\s+не\s+помогают/giu, 'что масла не помогают')
    .replace(/я\s+вам\s+«?в\s+руки\s+дал[аи]»?/giu, 'описаны в материале')
    .replace(/то\s+вы\s+всегда\s+увидите\s+результат/giu, 'результат обычно появляется постепенно')
    .replace(/А\s+что\s+бы\s+вы\s+хотели[^\n]*$/giu, '')
    .replace(/куда\s+вы\s+приехали/giu, 'при нахождении')
    .replace(/чем\s+Вам\s+хотелось\s+бы/giu, 'ожидаемого')
    .replace(/Вы\s+могли\s+быть\s+носителями\s*,?\s*переносчиками\s+и\s+не\s+болеть/giu, 'Взрослые могли быть носителями и не болеть')
    .replace(/а\s+вы\s+не\s+заразились\s+от\s+реб[её]нка/giu, 'при этом взрослые могли не заразиться от ребёнка')
    .replace(/Всегда\s+ваша\s+@\w+/giu, '')
    .replace(/Догадывались\s+ли\s+вы,\s*что/giu, 'Интересный факт:')
    .replace(/Ваш\s+домашний\s+лекарь/giu, 'Домашний помощник')
    .replace(/А\s+вы\s+подготовились\s+остановить\s+натиск\s+насекомых\?/giu, '')
    .replace(/это\s+не\s+относится\s+к\s+Вашему\s+случаю/giu, 'это зависит от конкретной ситуации')
    .replace(/о\s+которой\s+Вы\s+пишете/giu, 'которую иногда наблюдают после болезни')
    .replace(/Мононуклеозом\s+не\s+болели\s+дети\s+в\s+округе\?/giu, 'Следует учитывать возможные случаи мононуклеоза в окружении.')
    .replace(/Может\s+коклюш\s+в\s+такой\s+ситуации\?\s*Ночные\s+приступы\s+потому\s+что/giu, 'Следует исключить коклюш, особенно при ночных приступах.')
    .replace(/В\s+такой\s+ситуации\s+к\s+ротавирусу\s+е(?:ш|щ)е\s+до\s+кучи\s+и\s+флюс\s+надуло\?/giu, 'При сочетании кишечной инфекции и флюса')
    .replace(/уясните\s+это\s+себе[!.]*/giu, '')
    .replace(/Судя\s+по\s+возрасту,\s*в\s+такой\s+ситуации\s+молочница[!]*/giu, '')
    .replace(/Не\s+знаю,\s*понятно\s+ли\s+написал[аи][.!]*/giu, '')
    .replace(/Скоро\s+размещу\s+здесь/giu, '')
    .replace(/Ниже\s+я\s+напишу/giu, 'Ниже перечислены')
    .replace(/емли\s+вы\s+точно\s+знаете/giu, 'если точно известно')
    .replace(/Я\s+уже\s+выше\s+объяснял[аи]\s+почему\s+так\s+происходит/giu, 'Причина описана в соответствующей теме справочника')
    .replace(/(?:ещ[её]\s+раз\s+)?читай\s+здесь/giu, 'см. соответствующую тему справочника')
    .replace(/Про\s+.+?\s+когда\s+писал[аи],\s*все\s+способы\s+использования\s+с\s+ней\s+обозначил[аи]/giu, 'Способы применения перечислены в соответствующей теме справочника')
    .replace(/Что\s*-?\s*то\s+много\s+пишут\s+мне\s+про\s+[^!]+!\s*/giu, '')
    .replace(/Решил[аи]\s+написать,\s*если\s+кому\s+некогда\s+послушать\s+лекцию/giu, '')
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/\s+([,.!?;:])/g, '$1')
    .trim();

  if (!line || chatOnlyLine.test(line)) return '';
  if (/^(?:рецепт\s+)?см\.?\s*(?:здесь|по\s+ссылке)\s*$/iu.test(line)) return '';
  if (/^(?:Я|Мой|Моя|У\s+меня|Меня)\s/iu.test(line)) {
    line = `Из опыта автора: ${line}`;
  }
  return sentenceCase(line);
}

export function publicizeText(sourceText, topicTitle = '') {
  const lines = sourceText.split(/\r?\n/);
  const cleaned = [];

  for (const rawLine of lines) {
    const line = cleanLine(rawLine);
    if (!line) {
      if (cleaned.length && cleaned.at(-1) !== '') cleaned.push('');
      continue;
    }
    cleaned.push(line);
  }

  let text = cleaned
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();

  text = text
    .replace(/^Что\s*-?\s*то\s+много\s+пишут\s+автору\s+про\s+.+?[!.]\s*/iu, '')
    .replace(/Решил[аи]\s+написать,?\s*если\s+кому\s+некогда\s+послушать\s+лекцию/giu, '')
    .replace(/^По\s+поводу\s+вопроса\s*[:—–-]?\s*/iu, '')
    .replace(/^Имею\s+ввиду,\s*что\s*/iu, '')
    .replace(
      /^Простите,\s*никогда\s+не\s+пользуюсь\s+препаратами\s+аптечными[\s\S]*?Это\s+гормональный\s+препарат\s*/iu,
      'При оценке препарата важно смотреть на действующее вещество. В данном случае препарат является гормональным.\n'
    )
    .replace(
      /^Очень\s+похоже\s+на\s+укус\s+и\s+такая\s+реакция\s+пошла\s+Может\s+мошка\s+какая\s*/iu,
      'Такая реакция может возникнуть после укуса насекомого, например мошки.\n'
    )
    .replace(/Организатор\s+сильный/giu, 'Организм при достаточном ресурсе')
    .replace(/то\s+к\s+врачу\s+на\s+прокол\s+перепонки\s+едете/giu, 'необходима срочная очная помощь врача')
    .replace(/Думаю,\s*Вы\s+уже\s+знаете\s+как\s+справляться\s+с\s+жаром[!]*/giu, '')
    .replace(/Зачем\s+он\s+Вам[?!]+/giu, '')
    .replace(/А\s+что\s+бы\s+вы\s+хотели[^\n]*/giu, '')
    .replace(/Вы\s+могли\s+быть\s+носителями,?\s*переносчиками\s+и\s+не\s+болеть/giu, 'Взрослые могли быть носителями и не болеть')
    .replace(/емли\s+вы\s+точно\s+знаете/giu, 'если точно известно')
    .replace(/\n{3,}/g, '\n\n')
    .trim();

  if (!text) {
    return `Материал по теме «${topicTitle}» готовится к публикации.`;
  }
  return text;
}

